"""Forge - Runbook Executability Audit (goal #8).

Scans memory/ops/*.md for RUNBOOKS (prose procedures that should be executable),
classifies each as EXECUTABLE or PROSE_ONLY, and (with --fix) generates a safe
dry-run executor for every prose-only runbook so 0 remain prose-only.

Discovery (reproducible scope):
  A file counts as a runbook if its name contains 'runbook', OR ends with
  'checklist.md' / 'decision-tree.md'. Dated reports/snapshots/incidents are NOT runbooks.

Executable = any of:
  (a) a .py exists in memory/ops or memory/forge whose stem matches the runbook stem
      (date suffixes stripped), OR
  (b) the runbook body references an existing `python <path>.py` script, OR
  (c) an executor was generated by this tool under memory/forge/runbooks/<stem>.py.

Generated executors are SAFE: --dry-run (default) parses the source runbook's imperative
step lines and prints them without executing; exit 0. Real execution is OFF unless
FORGE_RUNBOOK_APPLY=1, and even then only whitelisted read-only prefixes run. This makes
the runbook machine-readable + executable-scaffolded without auto-running fleet commands.

Usage:
  python memory/forge/runbook_audit.py --scan    # report N found / M executable / K prose-only
  python memory/forge/runbook_audit.py --fix     # generate executors for prose-only, re-verify
  python memory/forge/runbook_audit.py --selftest
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OPS = ROOT / "memory" / "ops"
FORGE = ROOT / "memory" / "forge"
GEN_DIR = FORGE / "runbooks"
AUDIT_OUT = FORGE / "runbook-audit.json"

DATE_RE = re.compile(r"[-_]?\d{4}-\d{2}-\d{2}x?$")
STEP_RE = re.compile(r"^(?:\s*\d+[.)]|\s*[-*]\s+(?=python|elev\.py|schtasks|git\b))", re.IGNORECASE)
PYREF_RE = re.compile(r"(?:^|\s)(?:python[0-9.]*|py)\s+([A-Za-z0-9_./\\-]+\.py)")


def _strip_date(name):
    return DATE_RE.sub("", name).strip("-_ ")


def discover_runbooks(ops=OPS):
    names = []
    for f in sorted(Path(ops).glob("*.md")):
        n = f.name.lower()
        if "runbook" in n or n.endswith("checklist.md") or n.endswith("decision-tree.md"):
            names.append(f)
    return names


def _stem_matches_py(runbook_stem, search_dirs):
    target = runbook_stem.replace("-", "_").lower()
    for d in search_dirs:
        if not Path(d).exists():
            continue
        for py in Path(d).glob("*.py"):
            s = _strip_date(py.stem).replace("-", "_").lower()
            if s == target or (len(target) > 5 and (target in s or s in target)):
                return py
    return None


def classify(runbook, gen_dir=GEN_DIR):
    """Return (status, script_path_or_None). status in EXECUTABLE/PROSE_ONLY."""
    text = runbook.read_text(encoding="utf-8", errors="replace")
    stem = _strip_date(runbook.stem)
    # (a) matching .py by stem
    hit = _stem_matches_py(stem, [OPS, FORGE])
    if hit:
        return "EXECUTABLE", hit
    # (c) generated executor
    gen = GEN_DIR / (stem.replace("-", "_") + ".py")
    if gen.exists():
        return "EXECUTABLE", gen
    # (b) body references an existing python script
    for ref in PYREF_RE.findall(text):
        cand = ROOT / ref.replace("\\", "/")
        if cand.exists():
            return "EXECUTABLE", cand
    return "PROSE_ONLY", None


def extract_steps(text):
    steps = []
    for ln in text.splitlines():
        s = ln.strip()
        if not s:
            continue
        if STEP_RE.match(ln) or PYREF_RE.search(ln):
            # keep the imperative command portion
            m = PYREF_RE.search(ln)
            steps.append(m.group(1) if m else s.lstrip("0123456789.)- *"))
    return [s for s in steps if s]


EXECUTOR_TMPL = '''"""Auto-generated runbook executor (Forge goal #8) for %s.

SAFE default: --dry-run parses the source runbook and prints its imperative steps
without executing; exit 0. Real execution requires FORGE_RUNBOOK_APPLY=1 AND is
restricted to read-only prefixes. Never run fleet-mutating commands by accident.
"""
import os, re, sys
from pathlib import Path
SRC = Path(%r)
STEP_RE = re.compile(r"^(?:\\s*\\d+[.)]|\\s*[-*]\\s+(?=python|elev\\.py|schtasks|git\\b))", re.IGNORECASE)
PYREF_RE = re.compile(r"(?:^|\\s)(?:python[0-9.]*|py)\\s+([A-Za-z0-9_./\\\\-]+\\.py)")
READONLY_PREFIXES = ("python", "py", "git status", "git log", "schtasks /query", "type ", "dir ")

def steps():
    out = []
    if not SRC.exists():
        return out
    for ln in SRC.read_text(encoding="utf-8", errors="replace").splitlines():
        s = ln.strip()
        if not s:
            continue
        if STEP_RE.match(ln) or PYREF_RE.search(ln):
            m = PYREF_RE.search(ln)
            out.append(m.group(1) if m else s.lstrip("0123456789.)- *"))
    return [x for x in out if x]

def main():
    apply_mode = os.environ.get("FORGE_RUNBOOK_APPLY") == "1" and "--apply" in sys.argv
    dry = not apply_mode
    print(f"runbook executor: {SRC.name}")
    st = steps()
    if not st:
        print("  no imperative steps found; nothing to run (exit 0)")
        return 0
    for i, s in enumerate(st, 1):
        prefix = s.lower().split()[0] if s.split() else ""
        safe = any(s.lower().startswith(p) for p in READONLY_PREFIXES)
        if dry or not safe:
            tag = "dry-run" if dry else "SKIP(not-readonly)"
            print(f"  [{tag}] {i}. {s}")
        else:
            # read-only apply only
            import subprocess
            r = subprocess.run(s, shell=True, capture_output=True, text=True)
            print(f"  [ran rc={r.returncode}] {i}. {s}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
'''


def generate(runbook, gen_dir=GEN_DIR):
    gen_dir.mkdir(parents=True, exist_ok=True)
    stem = _strip_date(runbook.stem).replace("-", "_")
    out = gen_dir / (stem + ".py")
    body = EXECUTOR_TMPL % (runbook.name, str(runbook))
    out.write_text(body, encoding="utf-8")
    return out


def run_scan(write_json=True):
    books = discover_runbooks()
    rows = []
    for b in books:
        status, script = classify(b)
        rows.append({"runbook": b.name, "status": status,
                     "script": str(script.relative_to(ROOT)) if script else None})
    n = len(rows)
    m = sum(1 for r in rows if r["status"] == "EXECUTABLE")
    k = n - m
    report = {"total_runbooks": n, "executable": m, "prose_only": k,
              "rows": rows}
    if write_json:
        AUDIT_OUT.write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report


def run_fix():
    rep = run_scan(write_json=False)
    created = []
    for r in rep["rows"]:
        if r["status"] == "PROSE_ONLY":
            b = OPS / r["runbook"]
            p = generate(b)
            created.append(str(p.relative_to(ROOT)))
    # re-scan: generated executors must each --dry-run exit 0
    verify = []
    for c in created:
        import subprocess, sys as _s
        rc = _run_dry(c)
        verify.append({"script": c, "dry_run_exit": rc})
    final = run_scan(write_json=True)
    return {"created": created, "verify": verify,
            "total_runbooks": final["total_runbooks"],
            "executable": final["executable"],
            "prose_only": final["prose_only"]}


def _run_dry(relpath):
    import subprocess, sys as _s
    r = subprocess.run([_s.executable, str(ROOT / relpath), "--dry-run"],
                       capture_output=True, text=True)
    return r.returncode


def selftest():
    import tempfile
    print("=== runbook_audit.py SELFTEST ===")
    ok = True
    # craft a temp ops dir with 1 executable + 1 prose-only runbook
    tmp = Path(tempfile.mkdtemp(prefix="forge_rb_"))
    (tmp / "ops").mkdir()
    (tmp / "ops" / "foo-runbook.md").write_text("# Foo\n1. python memory/ops/existing.py\n", encoding="utf-8")
    (tmp / "ops" / "existing.py").write_text("import sys; sys.exit(0)\n", encoding="utf-8")
    (tmp / "ops" / "bar-runbook.md").write_text("# Bar\n1. restart the portal\n2. check logs\n", encoding="utf-8")
    books = discover_runbooks(tmp / "ops")
    names = sorted(b.name for b in books)
    ok &= names == ["bar-runbook.md", "foo-runbook.md"]
    print(f"  [{'PASS' if names==['bar-runbook.md','foo-runbook.md'] else 'FAIL'}] discovers 2 runbooks: {names}")
    # foo is executable (references existing.py); bar is prose-only
    sf, pf = classify(tmp / "ops" / "foo-runbook.md", tmp / "gen")
    sb, pb = classify(tmp / "ops" / "bar-runbook.md", tmp / "gen")
    ok &= sf == "EXECUTABLE" and sb == "PROSE_ONLY"
    print(f"  [{'PASS' if sf=='EXECUTABLE' and sb=='PROSE_ONLY' else 'FAIL'}] classify foo={sf} bar={sb}")
    # generate executor for bar, then it's executable and --dry-run exits 0
    genp = generate(tmp / "ops" / "bar-runbook.md", tmp / "gen")
    sb2, _ = classify(tmp / "ops" / "bar-runbook.md", tmp / "gen")
    ok &= sb2 == "EXECUTABLE"
    print(f"  [{'PASS' if sb2=='EXECUTABLE' else 'FAIL'}] after generate bar={sb2}")
    r = subprocess.run([sys.executable, str(genp), "--dry-run"], capture_output=True, text=True)
    ok &= r.returncode == 0
    print(f"  [{'PASS' if r.returncode==0 else 'FAIL'}] generated executor --dry-run exit={r.returncode}")
    print(f"  SELFTEST: {'PASS' if ok else 'FAIL'}")
    return ok


def main():
    import subprocess
    if "--selftest" in sys.argv:
        sys.exit(0 if selftest() else 1)
    if "--fix" in sys.argv:
        res = run_fix()
        print(json.dumps(res, indent=2))
        return
    rep = run_scan(write_json=True)
    print(f"runbooks found: {rep['total_runbooks']} | executable: {rep['executable']} | prose-only: {rep['prose_only']}")
    for r in rep["rows"]:
        print(f"  [{r['status']:11}] {r['runbook']}  -> {r['script'] or 'PROSE-ONLY'}")


if __name__ == "__main__":
    import subprocess
    main()
