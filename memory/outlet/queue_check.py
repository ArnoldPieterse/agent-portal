#!/usr/bin/env python3
"""Outlet content-queue validator + INDEX auto-updater.

Contract for every staged post (memory/outlet/queue/<date>-<slug>.md):
  Top key lines (before first '##'): date, kind, platform, status, topic
  Required sections ('##' headers):  Body, Rationale, Evidence, Notes for ship

Running this script:
  1. validates every entry -> prints violations, exit 1 if any else 0
  2. auto-regenerates memory/outlet/queue/INDEX.md from the live entries
Nothing publishes without a human approving the queue entry; this only checks shape.
"""
import re, sys, pathlib, datetime
from collections import Counter

HERE = pathlib.Path(__file__).resolve().parent
QUEUE = HERE / "queue"
INDEX = QUEUE / "INDEX.md"

REQUIRED_KEYS = ["date", "kind", "platform", "status", "topic"]
# section keyword -> human label (header text must contain the keyword, case-insensitive)
REQUIRED_SECTIONS = [("body", "Body"), ("rationale", "Rationale"),
                     ("evidence", "Evidence"), ("ship", "Notes for ship")]
ALLOWED_STATUS = {"drafting", "ready-for-human", "approved", "shipped"}
ALLOWED_KIND = {"upload", "reply", "repost"}
KEY_RE = re.compile(r"^([A-Za-z][A-Za-z -]*?):\s*(.*)$")


def parse_entry(path):
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    # preamble = up to first '##' header (H1 title + key lines live here)
    pre = []
    for ln in lines:
        if ln.lstrip().startswith("##"):
            break
        pre.append(ln)
    keys = {}
    for ln in pre:
        m = KEY_RE.match(ln.strip())
        if m:
            keys[m.group(1).strip().lower()] = m.group(2).strip()
    # sections: find all '##' headers and the content between them
    headers = []  # (title, content_str)
    cur_title, buf = None, []
    for ln in lines:
        s = ln.strip()
        if s.startswith("##"):
            if cur_title is not None:
                headers.append((cur_title, "\n".join(buf)))
            cur_title = s.lstrip("#").strip()
            buf = []
        elif cur_title is not None:
            buf.append(ln)
    if cur_title is not None:
        headers.append((cur_title, "\n".join(buf)))

    def has_section(kw):
        for title, content in headers:
            if kw in title.lower():
                # non-empty: at least one non-blank line that isn't itself a header
                real = [x for x in content.splitlines()
                        if x.strip() and not x.strip().startswith("##")]
                return len(real) > 0
        return False

    return keys, headers, has_section


def validate(path):
    v = []
    keys, headers, has_section = parse_entry(path)
    for k in REQUIRED_KEYS:
        if not keys.get(k):
            v.append(f"missing key line: {k}")
    if keys.get("status") and keys["status"] not in ALLOWED_STATUS:
        v.append(f"bad status '{keys['status']}' (allowed: {sorted(ALLOWED_STATUS)})")
    if keys.get("kind") and keys["kind"] not in ALLOWED_KIND:
        v.append(f"bad kind '{keys['kind']}' (allowed: {sorted(ALLOWED_KIND)})")
    for kw, label in REQUIRED_SECTIONS:
        if not has_section(kw):
            v.append(f"missing/empty section: {label}")
    return keys, v


def write_index(entries):
    order = {"drafting": 0, "ready-for-human": 1, "approved": 2, "shipped": 3}
    entries = sorted(entries, key=lambda e: (e["date"], e["name"]))
    sc = Counter(e["status"] for e in entries)
    L = []
    L.append("# Outlet Content Queue - INDEX")
    L.append("")
    L.append(f"Auto-generated by `python memory/outlet/queue_check.py` on {datetime.date.today().isoformat()}. "
             f"Do not hand-edit; edit the entry files instead.")
    L.append("")
    L.append(f"**{len(entries)} staged post(s):** " +
             ", ".join(f"{sc[s]} {s}" for s in ["drafting","ready-for-human","approved","shipped"] if sc.get(s)) or "(none)")
    L.append("")
    L.append("| date | topic | kind | platform | status |")
    L.append("|------|-------|------|----------|--------|")
    for e in entries:
        plat = (e["platform"] or "-").replace("|", "\\|")[:48]
        top = (e["topic"] or "-").replace("|", "\\|")[:60]
        L.append(f"| {e['date']} | [{top}](./{e['name']}) | {e['kind']} | {plat} | {e['status']} |")
    L.append("")
    L.append("Convention: every post carries date, kind, platform, status, topic + Body / Rationale / "
             "Evidence / Notes-for-ship sections. `queue_check.py` enforces this (0 violations) and rewrites this file.")
    INDEX.write_text("\n".join(L) + "\n", encoding="utf-8")


def main():
    if not QUEUE.is_dir():
        print(f"no queue dir at {QUEUE}"); return 0
    files = [p for p in sorted(QUEUE.glob("*.md")) if p.name != "INDEX.md"]
    total_v = 0
    entries = []
    for p in files:
        keys, v = validate(p)
        if v:
            print(f"FAIL {p.name}:")
            for x in v: print("   -", x)
            total_v += len(v)
        else:
            print(f"OK   {p.name}")
        entries.append({"name": p.name, "date": keys.get("date", "?"),
                        "topic": keys.get("topic", "?"), "kind": keys.get("kind", "?"),
                        "platform": keys.get("platform", ""), "status": keys.get("status", "?")})
    write_index(entries)
    print(f"\nqueue_check: {len(files)} entries, {total_v} violation(s); INDEX regenerated -> {INDEX.relative_to(HERE.parent.parent) if HERE.parent.parent in INDEX.parents else INDEX}")
    return 1 if total_v else 0


if __name__ == "__main__":
    sys.exit(main())