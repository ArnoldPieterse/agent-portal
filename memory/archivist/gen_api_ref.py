#!/usr/bin/env python3
"""archivist/gen_api_ref.py (cycle-2 goal 4; A#3 diff mode 2026-11-18).
Parses route definitions from agent_portal.py (do_GET/do_POST `p ==` / `p in` branches,
and /ui/* static) and regenerates memory/portal/api-reference.md.

Modes:
  python gen_api_ref.py            # regenerate only (exit 0)
  python gen_api_ref.py --diff     # regenerate + diff vs previous doc; removed routes are
                                   # BREAKING -> exit 2 (blocks the CI gate). Added routes
                                   # are reported, non-breaking.
  --src <file>                     # parse this file instead of agent_portal.py (testing)
"""
import os, re, sys, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
AP = os.path.join(ROOT, "agent_portal.py")
if "--src" in sys.argv:
    AP = sys.argv[sys.argv.index("--src") + 1]
SRC = open(AP, encoding="utf-8").read()

LINE_HIT = re.compile(r"\bp\s*(?:==|\bin\b)")
QUOTED = re.compile('["\']([^"\']+)["\']')


def routes_in(block):
    out = []
    for line in block.splitlines():
        if not LINE_HIT.search(line):
            continue
        for q in QUOTED.findall(line):
            if q.startswith("/"):
                out.append(q)
    return sorted(set(out))


def get_block(name):
    i = SRC.find("def %s(self):" % name)
    if i < 0: return ""
    j = SRC.find("\n    def ", i + 10)
    return SRC[i:j if j > 0 else len(SRC)]

GETS = routes_in(get_block("_do_GET")) + routes_in(get_block("do_GET"))
POSTS = routes_in(get_block("_do_POST")) + routes_in(get_block("do_POST"))
UI = re.findall(r'/ui/\*|ui/[a-z]+\.css', SRC)
seen, GETS2 = set(), []
for g in GETS:
    if g not in seen: seen.add(g); GETS2.append(g)

out = os.path.join(ROOT, "memory", "portal", "api-reference.md")

def build_doc():
    L = []
    L.append("# API reference (auto-generated by archivist/gen_api_ref.py)\n")
    L.append("Regenerated %s from agent_portal.py. Do not edit by hand - fix the generator.\n"
             % datetime.datetime.now().strftime("%Y-%m-%d %H:%M"))
    L.append("## GET (%d)\n" % len(GETS2))
    for g in GETS2: L.append("- `%s`" % g)
    L.append("\n## POST (%d)\n" % len(POSTS))
    for p in sorted(set(POSTS)): L.append("- `%s`" % p)
    L.append("\n## Static\n- `/ui/<name>.css|js` - UI modules (whitelisted extension, no traversal)\n")
    return "\n".join(L)

def parse_prev(path):
    """Return ({'GET': set, 'POST': set}) from a previously generated doc."""
    if not os.path.exists(path): return None
    sec, prev = None, {"GET": set(), "POST": set()}
    for ln in open(path, encoding="utf-8", errors="replace"):
        s = ln.strip()
        if s.startswith("## GET"): sec = "GET"
        elif s.startswith("## POST"): sec = "POST"
        elif s.startswith("## "): sec = None
        elif sec and s.startswith("- `"): prev[sec].add(s[3:-1])
    return prev

doc = build_doc()
if "--diff" in sys.argv or os.environ.get("GATE") == "1":
    prev = parse_prev(out)
    if prev is not None:
        cur = {"GET": set(GETS2), "POST": set(POSTS)}
        removed, added = [], []
        for m in ("GET", "POST"):
            removed += [f"{m} {r}" for r in sorted(prev[m] - cur[m])]
            added   += [f"{m} {r}" for r in sorted(cur[m] - prev[m])]
        if added: print("added (non-breaking): " + ", ".join(added))
        if removed:
            print("BREAKING - routes removed from agent_portal.py:")
            for r in removed: print("  -", r)
            with open(out, "w", encoding="utf-8") as fh: fh.write(doc)
            print("gen_api_ref: BLOCKED (breaking change)")
            sys.exit(2)
with open(out, "w", encoding="utf-8") as fh:
    fh.write(doc)
print("gen_api_ref: %d GET + %d POST routes -> %s" % (len(GETS2), len(set(POSTS)), os.path.relpath(out, ROOT)))
