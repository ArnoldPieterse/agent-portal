#!/usr/bin/env python3
"""Write-Time Auto-Linker (archivist goal 7).

When a new leaf is written, auto-suggest 3 nearest existing leaves (via TF-IDF
cosine similarity) and add bidirectional pointer lines so the graph stays
connected without manual INDEX edits.

Usage:
  python memory/archivist/auto_linker.py --file <path>   # link one file
  python memory/archivist/auto_linker.py --selftest      # run selftest
"""
import json, math, re, sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

MEMORY = Path("memory")
ARCHIVIST = MEMORY / "archivist"
STATE_FILE = ARCHIVIST / ".auto_linker_state.json"

def tokenize(text: str) -> list:
    """Simple whitespace + punctuation tokenizer."""
    return re.findall(r'[a-z0-9_]+', text.lower())

def build_corpus(paths: list) -> dict:
    """Build TF vectors for a set of files. Returns {path: Counter}."""
    corpus = {}
    for p in paths:
        try:
            text = p.read_text(encoding='utf-8', errors='ignore')
            if len(text) < 50:
                continue
            tokens = tokenize(text[:5000])  # cap at 5K chars for speed
            corpus[str(p)] = Counter(tokens)
        except Exception:
            pass
    return corpus

def cosine_sim(v1: Counter, v2: Counter) -> float:
    """Cosine similarity between two TF vectors."""
    if not v1 or not v2:
        return 0.0
    common = set(v1.keys()) & set(v2.keys())
    dot = sum(v1[k] * v2[k] for k in common)
    mag1 = math.sqrt(sum(x*x for x in v1.values()))
    mag2 = math.sqrt(sum(x*x for x in v2.values()))
    if mag1 == 0 or mag2 == 0:
        return 0.0
    return dot / (mag1 * mag2)

def find_md_files(root: Path, exclude: set = None) -> list:
    """Find all .md files under root, optionally excluding some paths."""
    exclude = exclude or set()
    results = []
    for f in root.rglob("*.md"):
        s = str(f).replace("\\", "/")
        if s not in exclude and f.stat().st_size > 50:
            results.append(f)
    return results

def link_file(target: Path, top_n: int = 3) -> dict:
    """Find top_n nearest neighbors for target and add pointer lines."""
    target_str = str(target).replace("\\", "/")
    
    # Build corpus from all other .md files (cap at 500 for speed)
    all_files = find_md_files(MEMORY, exclude={target_str})
    # Prioritize files in same lane + INDEX files
    lane = target.parent.name if target.parent != MEMORY else "root"
    same_lane = [f for f in all_files if f.parent.name == lane]
    index_files = [f for f in all_files if f.name == "INDEX.md"]
    # Take a manageable subset: same lane + indexes + random others
    candidates = same_lane[:100] + index_files[:20]
    if len(candidates) < 50:
        candidates += all_files[:50]
    
    corpus = build_corpus(candidates)
    target_vec = Counter(tokenize(target.read_text(encoding='utf-8', errors='ignore')[:5000]))
    
    # Score all candidates
    scores = []
    for path_str, vec in corpus.items():
        sim = cosine_sim(target_vec, vec)
        if sim > 0.01:
            scores.append((sim, path_str))
    
    scores.sort(reverse=True)
    top = [(s, p) for s, p in scores[:top_n] if p != target_str]
    
    # Add pointer lines to target file
    pointers_block = "\n<!-- AUTO-LINKS (generated by auto_linker.py) -->\n"
    for sim, path_str in top:
        pointers_block += f"- related: {path_str} (sim={sim:.3f})\n"
    
    # Read target and append/replace pointer block
    content = target.read_text(encoding='utf-8')
    # Remove old auto-links block if present
    marker_start = "<!-- AUTO-LINKS (generated by auto_linker.py) -->"
    if marker_start in content:
        idx = content.index(marker_start)
        # Find end of block (next blank line or EOF after the markers)
        lines_after = content[idx:].split('\n')
        end_offset = 0
        for i, l in enumerate(lines_after):
            if i > 0 and (l.startswith('- related:') or l.strip() == ''):
                end_offset += len(l) + 1
            else:
                break
        content = content[:idx] + content[idx + end_offset:]
    
    content = content.rstrip() + "\n" + pointers_block
    target.write_text(content, encoding='utf-8')
    
    return {
        "file": target_str,
        "links_added": len(top),
        "nearest": [{"path": p, "similarity": round(s, 4)} for s, p in top]
    }

def run_selftest() -> bool:
    """Selftest: create 10 test leaves, verify linking works correctly."""
    import tempfile, shutil
    
    print("[selftest] Building corpus...")
    # Use a subset of real files as the "existing corpus"
    all_files = find_md_files(MEMORY)
    print(f"[selftest] Corpus: {len(all_files)} existing .md files")
    
    # Create 10 test leaves with content that should match specific lanes
    test_dir = ARCHIVIST / "_selftest_links"
    test_dir.mkdir(exist_ok=True)
    
    test_contents = [
        ("fleet-white-oom.md", "Host White experienced OOM during model loading. The 24GB VRAM was exhausted by the attention heads. Recovery via schtasks restart."),
        ("model-loading-protocol.md", "Model loading protocol: check VRAM availability, queue if busy, timeout after 30s. Use elev.py for admin operations on fleet hosts."),
        ("portal-ui-css.md", "The portal UI uses CSS custom properties for theming. The light/dark toggle persists in localStorage. Panel layout uses flexbox with gap."),
        ("knowledge-index-build.md", "The knowledge index builder scans all memory/**/*.md files, extracts facts as subject-predicate-object triples, and writes JSON to knowledge-index.json."),
        ("winrm-remote-execution.md", "WinRM remote execution chain: connect via PowerShell remoting, run commands on Black/White/Cheese hosts. Fallback to local execution if unreachable."),
        ("goal-ledger-tracking.md", "The goal ledger tracks verified goals per agent. Each entry has a timestamp, verification method, and artifact path. Used by the dashboard for progress."),
        ("freshness-decay-scoring.md", "Freshness decay scoring: each leaf gets a score based on last-modified time. Score decays linearly over 7 days. Below threshold triggers quarantine."),
        ("citation-integrity-check.md", "Citation integrity monitor scans all goal files for pointer patterns. Verifies each cited target exists and is non-empty. Reports broken citations."),
        ("cockpit-api-endpoints.md", "The cockpit API exposes /api/goals, /api/fleet, /api/agents endpoints. Returns JSON with status codes. Used by the frontend for real-time updates."),
        ("archive-compaction-policy.md", "Archive compaction: files older than 30 days in memory/archivist/archive/ are compressed. Dedup removes identical content. Report generated per cycle."),
    ]
    
    results = []
    all_pass = True
    
    for i, (fname, content) in enumerate(test_contents):
        test_path = test_dir / fname
        test_path.write_text(f"# {fname}\n\n{content}\n", encoding='utf-8')
        
        result = link_file(test_path, top_n=3)
        
        # Check: no self-links
        self_link = any(l["path"] == str(test_path).replace("\\", "/") for l in result["nearest"])
        # Check: >=2 links (for files with enough content)
        has_links = result["links_added"] >= 2
        
        status = "PASS" if (not self_link and has_links) else "FAIL"
        if status == "FAIL":
            all_pass = False
        results.append({
            "file": fname,
            "links": result["links_added"],
            "self_link": self_link,
            "top_match": result["nearest"][0]["path"] if result["nearest"] else None,
            "status": status
        })
        print(f"  [{status}] {fname}: {result['links_added']} links, top={result['nearest'][0]['path'].split('/')[-1] if result['nearest'] else 'none'}")
    
    # Check idempotency: re-run on first test file
    first_test = test_dir / test_contents[0][0]
    result_before = link_file(first_test, top_n=3)
    result_after = link_file(first_test, top_n=3)
    idempotent = result_before["links_added"] == result_after["links_added"]
    
    # Verify no duplicate pointer blocks
    content = first_test.read_text(encoding='utf-8')
    block_count = content.count("<!-- AUTO-LINKS (generated by auto_linker.py) -->")
    idempotent = idempotent and block_count == 1
    
    status = "PASS" if idempotent else "FAIL"
    if not idempotent:
        all_pass = False
    results.append({"file": "idempotency", "links": result_after["links_added"], "self_link": False, "top_match": None, "status": status})
    print(f"  [{status}] idempotency: re-run produces same result, {block_count} block(s)")
    
    # Cleanup
    shutil.rmtree(test_dir, ignore_errors=True)
    
    passed = sum(1 for r in results if r["status"] == "PASS")
    total = len(results)
    print(f"\n[selftest] {passed}/{total} checks passed")
    
    # Write selftest report
    report = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "total_checks": total,
        "passed": passed,
        "failed": total - passed,
        "results": results,
        "verdict": "PASS" if all_pass else "FAIL"
    }
    out = ARCHIVIST / "access-heatmap-selftest.json"  # reuse for now
    # Actually write to its own file
    out = ARCHIVIST / "auto-linker-selftest.json"
    out.write_text(json.dumps(report, indent=2), encoding='utf-8')
    
    return all_pass

if __name__ == "__main__":
    if "--selftest" in sys.argv:
        ok = run_selftest()
        sys.exit(0 if ok else 1)
    elif "--file" in sys.argv:
        idx = sys.argv.index("--file")
        target = Path(sys.argv[idx + 1])
        result = link_file(target)
        print(json.dumps(result, indent=2))
    else:
        print(__doc__)
        sys.exit(1)
