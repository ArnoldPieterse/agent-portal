#!/usr/bin/env python3
"""Acceptance-Test Auto-Generator (Verifier Goal #6).

Parses goal lines from a lane's goals file, extracts acceptance criteria,
and emits runnable test stubs into memory/verifier/tests/.

Usage:
    python memory/verifier/acceptance_test_gen.py --agent verifier --count 5
    python memory/verifier/acceptance_test_gen.py --agent researcher --count 3
"""
import argparse, os, re, sys, subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TESTS_DIR = HERE / "tests"

GOAL_RE = re.compile(r'^(\d+)\.\s+\*\*(.+?)\*\*.*?Verified:\s*(.+)$', re.DOTALL)

def parse_goals(goals_file):
    """Parse numbered goal lines with Verified: criteria."""
    if not goals_file.exists():
        return []
    content = goals_file.read_text(encoding='utf-8')
    goals = []
    # Split by numbered items
    for m in re.finditer(r'^(\d+)\.\s+\*\*(.+?)\*\*[\s\S]*?Verified:\s*([^[\n(]+)', content, re.MULTILINE):
        num = int(m.group(1))
        title = m.group(2).strip()
        criterion = m.group(3).strip()
        goals.append((num, title, criterion))
    return goals

def generate_stub(agent, num, title, criterion, out_path):
    """Generate a runnable test stub for one goal."""
    safe_title = re.sub(r'[^a-zA-Z0-9]+', '_', title)[:50].strip('_')
    # Use explicit .format() with named placeholders to avoid f-string brace issues
    template = '''#!/usr/bin/env python3
"""Auto-generated acceptance test stub.
Agent: {agent}
Goal #{num}: {title}
Criterion: {criterion}
Generated by acceptance_test_gen.py
"""
import sys, os, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]

def test_goal_{num}_{safe_title}():
    """Verify: {criterion_short}"""
    # Auto-generated check: goal line exists in agent goals file
    goals_file = ROOT / "memory" / "goals" / "{agent}.md"
    assert goals_file.exists(), f"{{goals_file}} not found"
    content = goals_file.read_text(encoding="utf-8")
    assert "{num}.", f"Goal #{{num}} not in {{agent}}.md"
    return True

if __name__ == "__main__":
    try:
        test_goal_{num}_{safe_title}()
        print("PASS: {agent} goal #{num}")
        sys.exit(0)
    except AssertionError as e:
        print(f"FAIL: {{e}}")
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: {{type(e).__name__}}: {{e}}")
        sys.exit(2)
'''
    code = template.format(
        agent=agent,
        num=num,
        title=title,
        criterion=criterion[:200],
        criterion_short=criterion[:150],
        safe_title=safe_title
    )
    out_path.write_text(code, encoding='utf-8')
    return out_path

def main():
    parser = argparse.ArgumentParser(description="Acceptance-Test Auto-Generator")
    parser.add_argument('--agent', required=True, help='Agent name (e.g., verifier)')
    parser.add_argument('--count', type=int, default=5, help='Number of stubs to generate')
    args = parser.parse_args()

    goals_file = ROOT / "memory" / "goals" / f"{args.agent}.md"
    goals = parse_goals(goals_file)
    if not goals:
        print(f"ERROR: No goals parsed from {goals_file}")
        sys.exit(2)

    TESTS_DIR.mkdir(parents=True, exist_ok=True)
    generated = []
    for num, title, criterion in goals[:args.count]:
        out = TESTS_DIR / f"test_{args.agent}_goal{num}.py"
        generate_stub(args.agent, num, title, criterion, out)
        generated.append(out)
        print(f"  Generated: {out.name}")

    # Verify each stub is executable (passes or fails, not errors)
    print(f"\nVerifying {len(generated)} stubs are executable...")
    all_ok = True
    for path in generated:
        r = subprocess.run([sys.executable, str(path)], capture_output=True, text=True, timeout=10)
        status = "PASS" if r.returncode == 0 else ("FAIL" if r.returncode == 1 else "ERROR")
        if status == "ERROR":
            all_ok = False
            print(f"  [ERROR] {path.name}: rc={r.returncode} {r.stderr[:100]}")
        else:
            print(f"  [{status}] {path.name} (rc={r.returncode})")

    if all_ok:
        print(f"\nRESULT: PASS | {len(generated)} stubs generated, all executable (pass or fail, no errors)")
        sys.exit(0)
    else:
        print(f"\nRESULT: FAIL | some stubs errored")
        sys.exit(1)

if __name__ == "__main__":
    main()
