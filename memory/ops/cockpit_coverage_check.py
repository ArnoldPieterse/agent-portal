#!/usr/bin/env python3
"""
cockpit_coverage_check.py -- COVERAGE gate for the Cockpit feed (complements Verifier #2 staleness monitor)

WHY: The live-staleness monitor (memory/verifier/cockpit_staleness_monitor.py) checks ONLY the
top-level `ts` of memory/ops/cockpit-feed.json. Live root-cause (Researcher, 2026-11-24) proved
the feed can be FRESH by age while per-host data is missing: fleet-metrics is host WHITE only,
so the cockpit feed carries Red/Pale/Black with ALL metric fields = null. A freshness-only gate
then reports OK while 3 of 4 hosts are blind -> staleness != completeness.

This script adds the MISSING dimension: it asserts every expected host has all required metric
fields non-null (coverage), and that the feed age is within threshold (freshness). Overall verdict
is OK only when BOTH hold. For a closed-loop cockpit, "fresh" must mean "fresh AND complete".

Usage:
  python memory/ops/cockpit_coverage_check.py                 # check now (default 5min)
  python memory/ops/cockpit_coverage_check.py --self-test     # prove ok/stale/coverage branches
  python memory/ops/cockpit_coverage_check.py --hosts White,Red,Pale,Black

Exit codes:
  0 = FRESH AND COMPLETE (ok)
  1 = STALE (top-level ts age >= threshold)   [matches monitor]
  3 = COVERAGE BREACH (fresh but some host has null required fields)
  2 = usage / file-not-found error
"""
import argparse, json, os, sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent   # .../memory/ops/file.py -> repo root (dir containing 'memory')
FEED_FILE = REPO_ROOT / "memory" / "ops" / "cockpit-feed.json"
ALERT_DIR = REPO_ROOT / "memory" / "ops"
REQUIRED_FIELDS = ["vram_pct", "cpu_pct", "temp_c"]
DEFAULT_THRESHOLD_MIN = 5.0

def _now():
    return datetime.now(timezone.utc)

def _age_min(iso):
    if not iso:
        return None
    try:
        s = str(iso).replace("Z", "+00:00")
        return (_now().timestamp() - datetime.fromisoformat(s).timestamp()) / 60.0
    except (ValueError, TypeError):
        return None

def evaluate(feed, threshold_min, expected_hosts=None):
    """Return dict with fresh, complete, hosts_missing_fields, evidence."""
    now = _now()
    ts_age = _age_min(feed.get("ts"))
    # fallback to file mtime if ts absent/unparsable
    if ts_age is None and os.path.isfile(FEED_FILE):
        ts_age = (now.timestamp() - os.path.getmtime(FEED_FILE)) / 60.0
    fresh = ts_age is not None and ts_age < threshold_min

    hosts = feed.get("hosts", [])
    host_by_name = {h.get("host"): h for h in hosts if isinstance(h, dict)}
    universe = expected_hosts or list(host_by_name.keys())

    missing = {}   # host -> [fields that are null OR host absent]
    for hn in universe:
        h = host_by_name.get(hn)
        if h is None:
            missing[hn] = "<host absent from feed>"
            continue
        nulls = [f for f in REQUIRED_FIELDS if h.get(f) is None]
        if nulls:
            missing[hn] = nulls
    complete = len(missing) == 0

    pop = sum(1 for hn in universe if hn not in missing)
    evidence = (f"ts_age={('%.1f' % ts_age) if ts_age is not None else 'NA'}min, "
                f"hosts_expected={len(universe)}, hosts_complete={pop}, "
                f"hosts_degraded={sorted(missing.keys())}")
    return {"fresh": fresh, "complete": complete, "missing": missing,
            "ts_age_min": ts_age, "evidence": evidence}

def write_alert(reason, verdict):
    date_str = _now().strftime("%Y-%m-%d")
    p = ALERT_DIR / f"cockpit-coverage-alert-{date_str}.md"
    body = (f"# COCKPIT {reason} ALERT\n\n**Time:** {_now().isoformat()}\n"
            f"**Verdict:** {verdict}\n**Evidence:** {verdict.get('evidence')}\n\n"
            f"## Degraded hosts (null required fields)\n")
    for hn, miss in verdict["missing"].items():
        body += f"- **{hn}**: {miss}\n"
    body += ("\n## Action Required\nFleet collector reached only a subset of hosts "
             "(typically host WHITE). Confirm WinRM/probe reachability for the null hosts and that "
             "the collection schtask is live on White. See memory/researcher/cockpit-closedloop-rootcause-2026-11-24.md.\n\n"
             "*Auto-generated by cockpit_coverage_check.py*\n")
    p.write_text(body, encoding="utf-8")
    return str(p)

def run_self_test():
    print("=== SELF-TEST: cockpit_coverage_check.py ===\n")
    base = {"ts": _now().isoformat()}
    full = dict(base, hosts=[{"host": h, "vram_pct": 1.0, "cpu_pct": 2.0, "temp_c": 3.0} for h in ["White", "Red"]])
    deg  = dict(base, hosts=[{"host": "White", "vram_pct": 1.0, "cpu_pct": 2.0, "temp_c": 3.0},
                             {"host": "Red", "vram_pct": None, "cpu_pct": None, "temp_c": None}])
    stale= dict({"ts": (datetime(2000,1,1,tzinfo=timezone.utc)).isoformat()}, hosts=full["hosts"])

    r_full = evaluate(full, 5.0)
    t1 = r_full["fresh"] and r_full["complete"]
    print(f"T1 fresh+complete -> {t1}  ({r_full['evidence']})")

    r_deg  = evaluate(deg, 5.0)
    t2 = (not r_deg["complete"]) and r_deg["missing"].get("Red") == REQUIRED_FIELDS
    print(f"T2 coverage breach detected -> {t2}  ({r_deg['evidence']})")

    r_stale = evaluate(stale, 5.0)
    t3 = (not r_stale["fresh"]) and r_stale["complete"]
    print(f"T3 stale-but-complete -> {t3}  ({r_stale['evidence']})")

    ok = t1 and t2 and t3
    print(f"=== SELF-TEST RESULT: {'ALL PASS' if ok else 'FAIL'} ===")
    return 0 if ok else 1

def main():
    ap = argparse.ArgumentParser(description="Cockpit feed coverage + freshness gate")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD_MIN)
    ap.add_argument("--hosts", default=None, help="comma-separated expected hosts (default: all present in feed)")
    args = ap.parse_args()
    if args.self_test:
        sys.exit(run_self_test())
    if not os.path.isfile(FEED_FILE):
        print(f"FEED FILE NOT FOUND: {FEED_FILE}"); sys.exit(2)
    feed = json.loads(Path(FEED_FILE).read_text(encoding="utf-8"))
    expected = args.hosts.split(",") if args.hosts else None
    v = evaluate(feed, args.threshold, expected)
    if v["fresh"] and v["complete"]:
        print(f"OK: cockpit feed FRESH AND COMPLETE ({v['evidence']})"); sys.exit(0)
    if not v["fresh"]:
        print(f"STALE: {v['evidence']}")
        print("  " + write_alert("STALENESS", v)); sys.exit(1)
    print(f"COVERAGE BREACH (fresh but incomplete): {v['evidence']}")
    for hn, miss in v["missing"].items():
        print(f"    - {hn}: {miss}")
    print("  " + write_alert("COVERAGE", v)); sys.exit(3)

if __name__ == "__main__":
    main()
