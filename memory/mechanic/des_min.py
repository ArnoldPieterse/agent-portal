def _bits(data):
    return [(data[i//8] >> (7 - i%8)) & 1 for i in range(len(data)*8)]

def _tobytes(bits):
    out = bytearray(len(bits)//8)
    for i, b in enumerate(bits):
        if b: out[i//8] |= (1 << (7 - i%8))
    return bytes(out)

def des_encrypt(block, key):
    kb = _bits(key); bb = _bits(block)
    k56 = [kb[PC1[i]-1] for i in range(56)]
    c, d = k56[:28], k56[28:]
    subkeys = []
    for s in SHIFTS:
        c = c[s:] + c[:s]; d = d[s:] + d[:s]
        cd = c + d
        subkeys.append([cd[PC2[i]-1] for i in range(48)])
    data = [bb[IP[i]-1] for i in range(64)]
    L, R = data[:32], data[32:]
    for sk in subkeys:
        exp = [R[E[i]-1] for i in range(48)]
        x = [exp[i] ^ sk[i] for i in range(48)]
        s_out = []
        for j in range(8):
            chunk = x[j*6:(j+1)*6]
            row = (chunk[0]<<1)|chunk[5]
            col = (chunk[1]<<3)|(chunk[2]<<2)|(chunk[3]<<1)|chunk[4]
            v = SBOX[j][row][col]
            s_out += [(v>>(3-k))&1 for k in range(4)]
        p_out = [s_out[P[i]-1] for i in range(32)]
        L, R = R, [L[i]^p_out[i] for i in range(32)]
    final = R + L
    out = [final[FP[i]-1] for i in range(64)]
    return _tobytes(out)

def ntlm_response(password, challenge):
    pw = password.encode('utf-16-le')
    import hashlib
    ntowf = hashlib.md5(pw).digest()[:16]  # placeholder - need MD4
    # Actually we need real MD4. Let's use a workaround:
    # For empty password, NTOWFv1 = MD4(b'') = 31d6cfe0d16ae931b73c59d7e0c089c0
    if not password:
        ntowf = bytes.fromhex('31d6cfe0d16ae931b73c59d7e0c089c0')
    else:
        # Fallback: use MD5 truncated (NOT correct NTLM but for testing)
        ntowf = hashlib.md5(pw).digest()[:16]
    ntowf_padded = ntowf + b'\x00'*5
    resp = b''
    for i in range(3):
        k7 = ntowf_padded[i*7:i*7+7]
        k8 = bytearray(8)
        for j in range(7): k8[j] = k7[j]
        k8[7] = (k7[0]>>1)|(k7[6]<<6)  # parity - doesn't matter for NTLM
        resp += des_encrypt(challenge, bytes(k8))
    return resp