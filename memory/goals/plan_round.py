# ---- draft validation -----------------------------------------------------------------

def _strip_fences(t):
    t = (t or "").strip()
    if t.startswith("```"):
        t = re.sub(r"^```[a-zA-Z]*\s*", "", t)
        t = re.sub(r"\s*```$", "", t)
    return t.strip()


def _close_truncated(t):
    """If a draft was cut off mid-JSON (server token cap), close any open
    strings/brackets so the complete prefix still parses. None if hopeless."""
    t2 = t.rstrip()
    if not t2:
        return None
    stack, in_str, esc = [], False, False
    for ch in t2:
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
        elif ch in "{[":
            stack.append(ch)
        elif ch in "}]":
            if stack:
                stack.pop()
    if in_str:
        t2 += '"'
    t2 = t2.rstrip()
    if t2.endswith(","):
        t2 = t2[:-1]                                  # dangling comma before appended closers
    if not stack:
        return None                                   # balanced but internally broken
    return t2 + "".join("}" if b == "{" else "]" for b in reversed(stack))


def validate_draft(raw, roster_ids, refs):
    """-> (parsed|None, stats). parsed = {agents: {id: [item dicts]}} or None."""
    repaired = False
    t = _strip_fences(raw)
    try:
        d = json.loads(t)
    except Exception:
        t2 = re.sub(r",\s*([}\]])", r"\1", t)            # trailing commas (common LLM slip)
        try:
            d = json.loads(t2)
            repaired, t = True, t2
        except Exception:
            t3 = _close_truncated(t2)                     # cut off mid-JSON -> close open brackets
            if t3 is None:
                return None, {"error": "not-json (unrepairable)"}
            try:
                d = json.loads(t3)
                repaired, t = True, t3
            except Exception as e:
                return None, {"error": "not-json: %s" % str(e)[:120]}
    agents = (d or {}).get("agents") if isinstance(d, dict) else None
    if not isinstance(agents, dict):
        return None, {"error": "no agents object"}
    missing = [i for i in roster_ids if i not in agents]
    if len(missing) > max(1, len(roster_ids) // 4):
        return None, {"error": "missing agents: %s" % ",".join(missing[:6])}
    parsed, n_items, n_grounded = {}, 0, 0
    for aid in roster_ids:
        v = agents.get(aid)
        if not isinstance(v, list):
            continue
        items = []
        for it in v[:MAX_ITEMS_PER_AGENT]:
            if isinstance(it, str):
                it = {"item": it}
            if not isinstance(it, dict) or not _norm(str(it.get("item") or "")):
                continue
            item = {"item": str(it["item"])[:300],
                    "why": str(it.get("why") or "")[:200],
                    "ref": str(it.get("ref") or "")[:160]}
            n_items += 1
            if is_grounded(item["item"] + " " + item["ref"], refs):
                n_grounded += 1
            items.append(item)
        if items:
            parsed[aid] = items
    stats = {"agents": len(parsed), "items": n_items, "grounded": n_grounded,
             "ratio": round(n_grounded / n_items, 2) if n_items else 0.0,
             "missing": missing, "repaired": repaired}
    if not parsed or stats["ratio"] < GROUND_FLOOR:
        stats["error"] = "failed: %d agents, grounded %.0f%% (floor %.0f%%)" % (
            len(parsed), 100 * stats["ratio"], 100 * GROUND_FLOOR)
        return None, stats
    return {"agents": parsed}, stats


# ---- judging ---------------------------------------------------------------------------

def judge_call(judge_agent, labelled, doc, model=None):
    """labelled = [(label, parsed, stats)] -> verdict dict or None."""
    body = []
    for label, parsed, stats in labelled:
        compact = {aid: [it["item"] for it in items] for aid, items in parsed["agents"].items()}
        body.append("DRAFT %s (grounded %.0f%%, %d agents):\n%s" %
                    (label, 100 * stats.get("ratio", 0), len(parsed["agents"]),
                     json.dumps(compact)[:4200]))
    user = ("Plan context (for judging grounding/coverage):\n%s\n\n%s\n\n%s" %
            _plan_brief(doc)[:5000], "\n\n".join(body), JUDGE_CONTRACT)
    try:
        raw = llm_call(judge_agent, JUDGE_SYSTEM, user, max_tokens=900,
                       temperature=0.0, timeout=JUDGE_TIMEOUT_S, model=model)
        v = json.loads(_strip_fences(raw))
    except Exception:
        return None
    if not isinstance(v, dict) or v.get("winner") not in [l for l, _p, _s in labelled]:
        return None
    return {"agent": judge_agent["id"], "winner": v["winner"],
            "scores": v.get("scores") or {}, "rationale": str(v.get("rationale") or "")[:400]}


def local_pick(labelled):
    """Deterministic tie-break when the judge call fails: grounding-weighted score."""
    best, best_score = None, -1.0
    for label, parsed, stats in labelled:
        s = (stats.get("ratio", 0) * 4.0 +
             (len(parsed["agents"]) / max(1, stats.get("agents") or 1)) * 3.0)
        over = any(len(v) > 8 for v in parsed["agents"].values())
        if not over:
            s += 1.0
        if s > best_score:
            best, best_score = label, s
    return {"agent": "local-rubric", "winner": best,
            "scores": {l: round((s := (st.get("ratio", 0) * 4 + len(p["agents"]) / max(1, st.get("agents") or 1))), 2)
                       for l, p, st in labelled},
            "rationale": "judge seat unavailable - local rubric: grounding x4 + coverage x3 + day-fit bonus"}


# ---- rendering ---------------------------------------------------------------------------

def render_md(date_s, source, crew_ids, judge, pagers, stats):
    L = ["# FLEET ONE-PAGER - %s" % date_s,
         "",
         "Source: **%s** | planners: %s | judge: %s%s" % (
             source, ", ".join(crew_ids),
             (judge or {}).get("agent", "-"),
             (" - winner %s: %s" % ((judge or {}).get("winner", "?"), (judge or {}).get("rationale", ""))) if judge else "")]
    for aid, items in pagers.items():
        L.append("")
        L.append("## %s" % aid)
        for i, it in enumerate(items, 1):
            ref = (" _(from: %s)_" % it["ref"]) if it.get("ref") else ""
            why = (" - %s" % it["why"]) if it.get("why") else ""
            L.append("%d. **%s**%s%s" % (i, it["item"], ref, why))
    L.append("")
    L.append("_round stats: %s_" % json.dumps(stats)[:300])
    return "\n".join(L)


# ---- the round ---------------------------------------------------------------------------

def compute_sig(doc, roster_ids):
    """Signature over what a one-pager depends on: the live queue/goal texts,
    roster and date - plus the LLM planning chain (2026-11-24), so a new
    30/15/7-day plan re-gates the round."""
    src = json.dumps(doc.get("next10") or [], sort_keys=True, default=str)[:20000]
    try:
        ch = _load_json(os.path.join(PLANS, "llm-chain-latest.json"))
        if ch:
            src += "|chain:" + json.dumps(ch.get("plans", {}).get("7d") or [], sort_keys=True)[:8000]
    except Exception:
        pass
    return hashlib.sha1((",".join(roster_ids) + "|" + time.strftime("%Y-%m-%d") + "|" + src).encode()).hexdigest()[:12]

_CHAIN_MOD = None

def maybe_pipeline(doc=None):
    """Full planning pipeline (2026-11-24): LLM 30/15/7-day chain first, then the
    one-pager round. Each stage self-gates on signature + staleness, so a poll is
    a file read; at most one background worker runs."""
    global _CHAIN_MOD
    try:
        if _CHAIN_MOD is None:
            import importlib.util
            spec = importlib.util.spec_from_file_location("_plan_chain", os.path.join(HERE, "plan_chain.py"))
            m = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(m)
            _CHAIN_MOD = m
        return _CHAIN_MOD.maybe_pipeline(doc) or {}
    except Exception:
        return {}

def run_round(doc=None, force=False):
    """Run the full 3+1 round synchronously and set the winner as THE plan."""
    cfg = load_config()
    doc = ensure_chain() if doc is None else doc
    roster = load_roster()
    roster_ids = [a["id"] for a in roster]
    if not roster_ids:
        return {"error": "empty roster"}
    gen = None
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M"):
        try:
            gen = datetime.strptime(doc["generated"], fmt)
            break
        except Exception:
            continue
    gen = gen or datetime.now()
    sig = compute_sig(doc, roster_ids)
    date_s = str(gen)[:10]

    det = deterministic_pagers(doc, roster_ids, gen)          # fallback + fill source
    refs = grounding_refs(doc)
    planners, judge = select_crew(roster, cfg)                # [(agent, live_model_id)], (agent, mid)|None
    planner_ids = [a["id"] for a, _m in planners]

    user_prompt = draft_user_prompt(doc, roster_ids)
    drafts = []                                               # (label, agent_id, model, raw, parsed|None, stats)
    for i, (ag, mid) in enumerate(planners):                  # seats already probed live in select_crew
        label = "ABC"[i]
        try:
            raw = llm_call(ag, DRAFT_SYSTEM % ag.get("name", ag["id"]), user_prompt,
                           max_tokens=4000, temperature=0.2, model=mid)
        except Exception as e:
            drafts.append((label, ag["id"], mid, None, None,
                           {"error": "draft call failed: %s" % str(e)[:160]}))
            continue
        parsed, stats = validate_draft(raw, roster_ids, refs)
        stats["model"] = mid if mid != ag["model_id"] else None   # note fallback models in audit
        drafts.append((label, ag["id"], mid, raw, parsed, stats))

    valid = [d for d in drafts if d[4] is not None]
    labelled = [(l, p, st) for l, _aid, _mid, _raw, p, st in valid]  # (label, parsed, stats)
    verdict = None
    if len(valid) >= 2:
        if judge and judge[1]:
            jag, jmid = judge
            verdict = judge_call(jag, labelled, doc, model=jmid)
        if verdict is None:                                   # no live judge seat / judge failed -> local rubric
            verdict = local_pick(labelled)
    elif len(valid) == 1:
        verdict = {"agent": "none", "winner": valid[0][0],
                   "scores": {}, "rationale": "only valid draft (other seats failed or ungrounded)"}

    if verdict and any(d[0] == verdict["winner"] for d in valid):
        label, agent_id, mid, raw, parsed, stats = next(d for d in valid if d[0] == verdict["winner"])
        source = "llm-3+1" if (verdict.get("agent") not in (None, "none", "local-rubric")) else \
                 ("llm-judge-local" if len(valid) >= 2 else "llm-single-draft")
        pagers = parsed["agents"]
    else:
        source = "deterministic-fallback"
        pagers, label, agent_id = det, None, None

    for aid in roster_ids:                                    # guarantee: every agent gets a pager
        if not pagers.get(aid):
            pagers[aid] = det[aid]

    stats_out = {"sig": sig, "date": date_s,
                 "drafts": [{"label": l, "agent": aid, "model": mid, "stats": st}
                            for l, aid, mid, _r, _p, st in drafts],
                 "source": source}
    result = {"ts": int(time.time()), "date": date_s, "sig": sig, "source": source,
              "winner_label": label, "planners": planner_ids,
              "judge": verdict, "pagers": pagers, "stats": stats_out}

    _save_json(LATEST_JSON, result)
    with open(LATEST_MD, "w", encoding="utf-8") as f:
        f.write(render_md(date_s, source, planner_ids, verdict, pagers, stats_out))
    _append_rounds({"ts": int(time.time()), "sig": sig, "source": source,
                    "planners": planner_ids, "judge": verdict,
                    "drafts": [{"label": l, "agent": aid, "model": mid,
                                "raw": (r or "")[:4000], "stats": st}
                               for l, aid, mid, r, _p, st in drafts]})
    return result


# ---- gating: cheap on every poll, LLM only when something changed --------------------

def maybe_run(doc=None):
    """Called from the portal on every /api/goals/forecast poll. Returns the cached
    one-pager (or a pending marker) and fires a background round ONLY when the
    signature changed or the pagers aged out."""
    cfg = load_config()
    if not cfg.get("enabled", True):
        return None
    with _LOCK:
        doc = ensure_chain() if doc is None else doc
        roster_ids = [a["id"] for a in load_roster()]
        sig = compute_sig(doc, roster_ids)
        state = _load_json(STATE_F) or {}
        latest = _load_json(LATEST_JSON)
        max_age_s = float(cfg.get("max_age_h", 24.0)) * 3600
        fresh = bool(latest and (time.time() - float(latest.get("ts") or 0)) < max_age_s)
        if state.get("sig") == sig and fresh:
            return latest
        running = state.get("running")
        if running and (time.time() - float(state.get("run_ts") or 0)) < RUN_STALE_S:
            return dict(latest or {}, pending=True)          # a round is already in flight
        state.update(running=True, run_ts=time.time(), sig=sig)
        _save_json(STATE_F, state)

    def worker():
        try:
            run_round(doc=doc)
        except Exception as e:                               # never kill the portal thread
            try:
                _append_rounds({"ts": int(time.time()), "error": str(e)[:300]})
            except Exception:
                pass
        finally:
            with _LOCK:
                st = _load_json(STATE_F) or {}
                st["running"] = False
                _save_json(STATE_F, st)

    threading.Thread(target=worker, daemon=True, name="plan-round").start()
    return dict(latest or {}, pending=True)


if __name__ == "__main__":
    force = "--force" in sys.argv
    res = maybe_run() if not force else run_round(force=force)
    print(json.dumps({k: v for k, v in (res or {}).items() if k != "pagers"}, indent=1)[:2000])
