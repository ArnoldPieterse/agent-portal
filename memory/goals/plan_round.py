#!/usr/bin/env python3
"""Final planning round - the per-agent ONE-PAGER (2026-11-24, Orchestrator seat).

Closes the 30 -> 15 -> 7 day derivation chain with the last planning step: a
one-pager per agent listing the items that agent must do TODAY. Produced by an
LLM round of 3+1 calls:

  1. ensure the deterministic chain exists - check the current 30-day plan in
     next10.json; if none (or empty), forecast_engine.refresh() rebuilds
     30 -> 15 -> 7 from live state before anything else runs
  2. THREE independent drafts, each generated by a DIFFERENT roster agent on
     its own studio seat (default crew: orchestrator + designer + researcher -
     ops, architecture and analysis perspectives)
  3. a FOURTH call by the judge agent (default: verifier) scores the three
     drafts against a rubric and selects the winner; the winner is set as THE
     plan (one-pager-latest.json / .md)

Guard rails (deterministic, stdlib only - safe under pythonw schtask):
  - signature gating: the round re-runs only when the date, the 30-day plan
    sig or the per-agent goal state changes, or the pagers age out (default
    24 h) - repeated /api polls cost zero LLM calls
  - grounding check: every draft item must trace to a real 7-day step, open
    goal or next-10 queue item; ungrounded drafts are dropped before judging
  - deterministic fallback: if no seat answers, pagers are built straight
    from the 7-day plan + open goals (source labelled "deterministic-fallback")
  - judge failure -> local rubric tie-break (grounding-weighted score)
  - every roster agent is guaranteed a pager (agents the LLM missed are
    filled from the deterministic slice)
  - in-progress lock with stale-run recovery: portal restarts neither
    double-fire the round nor deadlock it
  - full audit: all three raw drafts + the verdict appended to rounds.jsonl,
    so planner quality can be calibrated over time

Outputs (memory/goals/plans/):
  one-pager-latest.json   machine-readable current plan (portal serves it)
  one-pager-latest.md     the human one-pager, one section per agent
  rounds.jsonl            audit trail of every round
  plan-round-state.json   sig / in-progress lock / last verdict
  config.json             optional overrides: planners, judge, max_age_h, enabled

Usage:
  python memory/goals/plan_round.py [--force]   # run one full round now
"""
