def _day_owner(doc):
    """agent lane that owns each 7-day entry (via its parent 30-day outcome)."""
    lane_by_name = {o.get("name"): o.get("lane") for o in ((doc.get("plan") or {}).get("outcomes_30d") or [])}
    try:  # LLM chain (2026-11-24): its 30-day names may differ from the computed ones
        ch = _load_json(os.path.join(PLANS, "llm-chain-latest.json"))
        for o in (ch or {}).get("plans", {}).get("30d") or []:
            lane_by_name.setdefault(o.get("name"), o.get("lane"))
    except Exception:
        pass
    out = {}
    for e in (doc.get("plan") or {}).get("outcomes_7d") or []:
        base = (e.get("name") or "").replace(" - prep", "")
        out[e.get("name")] = lane_by_name.get(base)
    return out


def _today_items(doc, agent_id, gen):
    """Deterministic today-slice for one agent: next-10 items due within 24 h,
    7-day steps pinned to day 0/1 owned by its lane, then remaining open goals."""
    items = []
    seen = set()

    def add(item, why, ref):
        k = _norm(item)
        if k in seen or not item:
            return
        core = re.sub(r"^(advance #\d+:|continue open goal:)\s*", "", item, flags=re.I)
        for ex in items:  # same goal already listed (queue vs ledger) -> skip
            if is_grounded(core, [ex["item"], ex["ref"]]):
                return
        seen.add(k)
        items.append({"item": item[:300], "why": (why or "")[:200], "ref": (ref or "")[:160]})

    for it in doc.get("next10") or []:
        if it.get("agent") != agent_id:
            continue
        try:
            eta = datetime.strptime(it["eta"], "%Y-%m-%d %H:%M")
        except Exception:
            continue
        if (eta - gen).total_seconds() <= 86400:
            add("Advance #%d: %s" % (it.get("rank", 0), (it.get("title") or it.get("goal") or "")[:120]),
                it.get("why") or "next-10 queue item due within 24 h",
                it.get("title") or it.get("goal") or "")
    owner = _day_owner(doc)
    o7 = (doc.get("plan") or {}).get("outcomes_7d") or []
    try:  # LLM chain (2026-11-24): its 7-day steps are today's plan of record
        ch = _load_json(os.path.join(PLANS, "llm-chain-latest.json"))
        if ch and ch.get("plans", {}).get("7d"):
            o7 = ch["plans"]["7d"]
    except Exception:
        pass
    for e in o7:
        if owner.get(e.get("name")) != agent_id:
            continue
        for s in e.get("steps") or []:
            m = re.search(r"day (\d+)", s.get("days") or "")
            if m and int(m.group(1)) <= 1:
                add("%s (%s: %s)" % (s["text"][:140], e.get("name", "plan step")[:40], s.get("days", "day 0")),
                    "7-day plan step pinned to today",
                    "%s / %s" % (e.get("name", ""), s["text"][:80]))
    for g in _ledger().get(agent_id) or []:
        if g.get("status") == "reached":
            continue
        gt = re.sub(r"\*+", "", g.get("text") or "")[:160]
        add("Continue open goal: %s" % gt,
            "open on the lane, outside today's queue - keep momentum",
            gt)
        if len(items) >= MAX_ITEMS_PER_AGENT:
            break
    if not items:
        add("No plan items due today - triage open goals and pick the next step from the 7-day plan",
            "empty slice; keep the lane moving", "")
    return items[:MAX_ITEMS_PER_AGENT]


def deterministic_pagers(doc, roster_ids, gen=None):
    gen = gen or datetime.now()
    return {aid: _today_items(doc, aid, gen) for aid in roster_ids}


# ---- grounding -----------------------------------------------------------------

def grounding_refs(doc):
    """The set of real plan/goal texts an item may trace to."""
    refs = []
    plan = doc.get("plan") or {}
    for e in plan.get("outcomes_7d") or []:
        refs.append(e.get("name", ""))
        for s in e.get("steps") or []:
            refs.append(s.get("text", ""))
    for e in plan.get("outcomes_15d") or []:
        for s in e.get("steps") or []:
            refs.append(s.get("text", ""))
    for o in plan.get("outcomes_30d") or []:
        refs.append(o.get("name", ""))
    for it in doc.get("next10") or []:
        refs.append(it.get("title", ""))
        refs.append(it.get("goal", ""))
    for goals in _ledger().values():
        for g in goals:
            refs.append(g.get("text", ""))
    try:  # LLM planning chain (2026-11-24): selected plans are ground truth too
        ch = _load_json(os.path.join(PLANS, "llm-chain-latest.json"))
        for hz in ("30d", "15d", "7d"):
            for e in (ch or {}).get("plans", {}).get(hz) or []:
                refs.append(str(e.get("name") or ""))
                if hz == "30d":
                    refs.extend(str(g) for g in e.get("gates") or [])
                else:
                    refs.extend(str(s.get("text") or "") for s in e.get("steps") or [])
    except Exception:
        pass
    return [r for r in refs if _norm(r)]


def is_grounded(text, refs):
    t = _norm(text)
    if not t:
        return False
    toks = {w for w in t.split() if len(w) > 3}
    for r in refs:
        rn = _norm(r)
        if rn in t or t in rn:
            return True
        rtoks = {w for w in rn.split() if len(w) > 3}
        if toks and rtoks:
            inter = len(toks & rtoks)
            if inter / min(len(toks), len(rtoks)) >= 0.6:
                return True
    return False


# ---- crew selection ----------------------------------------------------------------

def select_crew(roster, cfg):
    """3 SEAT-AWARE planner agents + 1 judge (never a planner). Preference order
    comes from config, then roster file order; a candidate whose seat has no live
    model right now is skipped and the next one takes its place. Returns planners
    as [(agent, model_id)] and judge as (agent, model_id) or None."""
    by_id = {a["id"]: a for a in roster}
    probed, mcache = {}, {}
    wanted = list(cfg.get("planners") or []) + [a["id"] for a in roster]
    planners = []
    for pid in wanted:
        if len(planners) >= 3:
            break
        a = by_id.get(pid)
        if not a or any(a["id"] == p[0]["id"] for p in planners):
            continue
        mid = seat_model(a, probed, mcache)
        if mid:
            planners.append((a, mid))
    judge = None
    jwant = [cfg.get("judge") or DEFAULT_JUDGE] + wanted
    for pid in jwant:
        a = by_id.get(pid)
        if not a or any(a["id"] == p[0]["id"] for p in planners):
            continue
        mid = probed.get(a["id"]) or seat_model(a, probed, mcache)
        judge = (a, mid) if mid else None
        break
    return planners, judge


