def _fmt_outcomes(entries):
    L = []
    for o in entries:
        gates = ", ".join(o.get("gates") or []) or "-"
        L.append("- %s: %s | %s | lane %s | gates: %s" % (
            o.get("name"), o.get("window"), o.get("status"), o.get("lane", "?"), gates[:200]))
    return "\n".join(L)


def _fmt_entries(entries):
    L = []
    for e in entries:
        L.append("- %s%s: %s | %s" % (e.get("name"),
                                      (" -> parent " + e["parent"]) if e.get("parent") else "",
                                      e.get("window"), e.get("status")))
        for s in e.get("steps") or []:
            L.append("    %s: %s" % (s.get("days"), s.get("text")))
    return "\n".join(L)


