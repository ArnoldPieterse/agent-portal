"""plan_chain.py - LLM planning chain (2026-11-24).

The 30/15/7-day plans are generated by the same 3+1 round as the one-pager:
three planner seats draft each horizon independently, a judge seat (never one of
the planners) picks the best; when no live judge exists, a local rubric decides.
Each round conditions on the SELECTED plan of the previous horizon:

    live state -> [30d round] -> selected 30d -> [15d round] -> selected 15d -> [7d round]

The deterministic chain (forecast_plan.build_plan) stays as grounding reference
and per-horizon fallback: a horizon with no valid LLM draft keeps the computed
plan and is labelled "deterministic-fallback", so the pipeline degrades
gracefully instead of stalling.

State (all under memory/goals/plans/):
    llm-chain-latest.json   selected chain + round metadata (served via /api/goals/forecast)
    llm-chain-latest.md     human-readable version
    chain-state.json        sig + in-flight marker (gating, like plan-round-state.json)
    chain-rounds.jsonl      audit trail

Gating: signature over the deterministic 30-day plan sig + date + roster; max age
24 h. LLM work runs in a background thread so /api/goals/forecast stays a file read.
"""
