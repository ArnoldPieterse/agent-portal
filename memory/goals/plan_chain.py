def brief(doc):
    """Compact ground-truth brief every draft is conditioned on."""
    plan = doc.get("plan") or {}
    L = []
    fl = doc.get("fleet") or {}
    L.append("Fleet: %s/%s goals done (%s%%) | throughput ~%s goals/h" % (
        fl.get("done", "?"), fl.get("total", "?"), fl.get("pct", "?"),
        doc.get("throughput_goals_per_hour", "?")))
    cc = plan.get("capability_chain") or []
    if cc:
        L.append("Capability chain: " + " | ".join(
            "%s [%s]%s" % (c.get("name"), c.get("status"),
                           (" via " + c["via"]) if c.get("via") else "") for c in cc[:10]))
    n10 = doc.get("next10") or []
    if n10:
        L.append("Next-10 queue: " + "; ".join(
            "#%s [%s] %s ETA %s" % (it.get("rank", i), it.get("agent"),
                                    (it.get("title") or it.get("goal") or "")[:60],
                                    it.get("eta", "?")) for i, it in enumerate(n10[:8])))
    by_agent = {}
    for it in plan.get("planned") or []:
        a = it.get("agent") or "?"
        by_agent.setdefault(a, []).append((it.get("title") or it.get("goal") or "")[:70])
    if by_agent:
        L.append("Open work per agent: " + "; ".join(
            "%s: %s" % (a, " | ".join(v[:4])) for a, v in sorted(by_agent.items())))
    oc = plan.get("outcomes_30d") or []
    if oc:
        L.append("Known outcome catalog: " + "; ".join(
            "%s (%s)%s" % (o.get("name"), o.get("window"),
                          (" gates: " + ", ".join(o.get("gates") or []))[:90] if o.get("gates") else "")
            for o in oc))
    return "\n".join(L)[:3200]


def refs_30(doc):
    """Grounding refs for the 30d round: catalog, capabilities, queue, open goals."""
    plan = doc.get("plan") or []
    refs = []
    for o in plan.get("outcomes_30d") or []:
        refs.append(o.get("name", ""))
        refs.extend(o.get("gates") or [])
    for c in plan.get("capability_chain") or []:
        refs.append(c.get("name", ""))
    for it in doc.get("next10") or []:
        refs.append(it.get("title", ""))
        refs.append(it.get("goal", ""))
    for it in plan.get("planned") or []:
        refs.append(it.get("title", "") or it.get("goal", ""))
    try:
        for goals in _pr()._ledger().values():
            for g in goals:
                refs.append(g.get("text", ""))
    except Exception:
        pass
    return [r for r in refs if isinstance(r, str) and r.strip()]


