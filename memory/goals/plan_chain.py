# ---- plan_round access (own instance, file-based load) -------------------------

def _pr():
    global _PR
    if _PR is None:
        import importlib.util
        spec = importlib.util.spec_from_file_location("_plan_round_for_chain",
                                                      os.path.join(HERE, "plan_round.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        _PR = m
    return _PR


def load_config():
    cfg = dict(_pr().DEFAULTS)
    try:
        cfg.update(json.load(open(os.path.join(PLANS, "config.json"), encoding="utf-8")))
    except Exception:
        pass
    return cfg


# ---- small helpers -------------------------------------------------------------

def _load_json(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def _save_json(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=1, ensure_ascii=False)
    os.replace(tmp, path)


def _append_rounds(entry):
    try:
        with open(ROUNDS_F, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except Exception:
        pass


def load_chain():
    return _load_json(LLM_CHAIN_JSON)


def chain_sig(doc, roster_ids):
    """Signature over what the chain depends on: deterministic plan sig + date + roster."""
    pm = ((doc or {}).get("plan") or {}).get("plan_meta") or {}
    src = "%s|%s|%s" % (pm.get("sig", ""), time.strftime("%Y-%m-%d"), ",".join(roster_ids))
    return hashlib.sha1(src.encode()).hexdigest()[:12]


def _chain_age_ok(cfg, sig):
    ch = load_chain()
    if not ch or ch.get("sig") != sig:
        return False
    try:
        return (time.time() - os.path.getmtime(LLM_CHAIN_JSON)) < cfg.get("max_age_h", 24.0) * 3600
    except OSError:
        return False


def _chain_running():
    st = _load_json(CHAIN_STATE_F) or {}
    return bool(st.get("running")) and (time.time() - (st.get("run_ts") or 0)) < RUN_STALE_S


