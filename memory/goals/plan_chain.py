def render_md(r):
    L = ["# LLM planning chain - %s" % r.get("date"), "",
         "sig `%s` | sources: 30d=%s 15d=%s 7d=%s" % (
             r.get("sig"), r["sources"]["30d"], r["sources"]["15d"], r["sources"]["7d"]), ""]
    for hz, title in (("30d", "30-day plan"), ("15d", "15-day plan"), ("7d", "7-day plan")):
        rd = r["rounds"][hz]
        j = rd.get("judge") or {}
        L.append("## %s - %s (%s)" % (title, r["sources"][hz],
                                       (j.get("winner") + " by " + j.get("agent", "?")) if j else "fallback"))
        if j.get("rationale"):
            L.append("> " + j["rationale"])
        for e in r["plans"][hz]:
            if hz == "30d":
                gates = ", ".join(e.get("gates") or []) or "-"
                cc = " [closes cycle]" if e.get("cycle_closing") else ""
                L.append("- **%s** (%s, lane %s)%s - %s | gates: %s" % (
                    e["name"], e["window"], e.get("lane", "?"), cc,
                    (e.get("note") or e.get("status"))[:160], gates[:200]))
            else:
                par = " -> parent %s" % e["parent"] if e.get("parent") else ""
                L.append("- **%s**%s (%s) - %s" % (e["name"], par, e["window"], (e.get("status") or "")[:160]))
                for s in e.get("steps") or []:
                    L.append("  - %s: %s" % (s["days"], s["text"][:200]))
        L.append("")
    return "\n".join(L)


def run_chain(doc=None, force=False):
    """Run the 30d -> 15d -> 7d rounds and persist the selected chain."""
    pr = _pr()
    doc = doc or pr.ensure_chain()
    roster = pr.load_roster()
    roster_ids = [a["id"] for a in roster]
    cfg = load_config()
    crew = pr.select_crew(roster, {"planners": cfg.get("chain_planners") or cfg.get("planners"),
                                   "judge": cfg.get("chain_judge") or cfg.get("judge")})
    plan = doc.get("plan") or {}
    det30 = plan.get("outcomes_30d") or []
    det15 = plan.get("outcomes_15d") or []
    det7 = plan.get("outcomes_7d") or []
    sig = chain_sig(doc, roster_ids)
    refs = refs_30(doc)

    sel30, src30, v30, d30 = _round(
        "30d", S30_SYSTEM, user_30(doc, roster_ids),
        lambda raw: validate_30d(raw, refs, roster_ids),
        [o.get("name") for o in det30 if o.get("name")], crew)
    if sel30 is None:
        sel30 = det30
    sel15, src15, v15, d15 = _round(
        "15d", S15_SYSTEM, user_15(doc, sel30),
        lambda raw: _validate_derived(raw, sel30, refs, 15),
        [e.get("name") for e in sel30 if e.get("name")], crew)
    if sel15 is None:
        sel15 = det15
    sel7, src7, v7, d7 = _round(
        "7d", S7_SYSTEM, user_7(doc, sel15),
        lambda raw: _validate_derived(raw, sel15, refs, 7),
        [e.get("name") for e in sel15 if e.get("name")], crew)
    if sel7 is None:
        sel7 = det7

    result = {"ts": time.strftime("%Y-%m-%d %H:%M:%S"), "date": time.strftime("%Y-%m-%d"),
              "sig": sig, "planners": [a[0]["id"] for a in crew[0]],
              "judge": (crew[1][0]["id"] if crew[1] else None),
              "sources": {"30d": src30, "15d": src15, "7d": src7},
              "rounds": {"30d": {"judge": v30, "drafts": d30},
                         "15d": {"judge": v15, "drafts": d15},
                         "7d": {"judge": v7, "drafts": d7}},
              "plans": {"30d": sel30, "15d": sel15, "7d": sel7}}

    ch = load_chain()
    same = bool(ch and ch.get("sig") == sig and ch.get("plans") == result["plans"])
    if not same:
        _save_json(LLM_CHAIN_JSON, result)
        with open(LLM_CHAIN_MD, "w", encoding="utf-8") as f:
            f.write(render_md(result))
        _append_rounds({"ts": result["ts"], "sig": sig, "sources": result["sources"],
                        "winners": {hz: ((result["rounds"][hz].get("judge") or {}).get("winner"))
                                    for hz in ("30d", "15d", "7d")}})
    return result


# ---- gating + pipeline -----------------------------------------------------------------------

def _fire_chain_worker(roster_ids):
    def worker():
        try:
            run_chain()
        except Exception:
            pass
        finally:
            try:
                st = {"sig": chain_sig(_pr().ensure_chain(), roster_ids), "running": False,
                      "run_ts": time.time()}
            except Exception:
                st = {"sig": "", "running": False, "run_ts": time.time()}
            _save_json(CHAIN_STATE_F, st)
            try:  # re-gate the one-pager against the (possibly new) chain
                _pr().maybe_run()
            except Exception:
                pass
    threading.Thread(target=worker, daemon=True).start()


def maybe_chain(doc=None):
    """Gated entry point: fresh -> cached file read; stale -> background round."""
    pr = _pr()
    cfg = load_config()
    if not cfg.get("enabled", True):
        return {}
    with _LOCK:
        doc = doc or pr.ensure_chain()
        roster_ids = [a["id"] for a in pr.load_roster()]
        sig = chain_sig(doc, roster_ids)
        ch = load_chain()
        if _chain_age_ok(cfg, sig):
            return {"llm_chain": ch}
        if _chain_running():
            return {"llm_chain": ch, "pending": True}
        _save_json(CHAIN_STATE_F, {"sig": sig, "running": True, "run_ts": time.time()})
        _fire_chain_worker(roster_ids)
        return {"llm_chain": ch, "pending": True}


def maybe_pipeline(doc=None):
    """Portal entry point: LLM chain first (30/15/7-day), then the one-pager round.
    Each stage self-gates on signature + staleness; while the chain is in flight the
    one-pager is deferred (its sig includes the chain ts, so it re-fires afterwards)."""
    pr = _pr()
    cfg = load_config()
    if not cfg.get("enabled", True):
        return {}
    with _PIPE_LOCK:
        doc = doc or pr.ensure_chain()
        roster_ids = [a["id"] for a in pr.load_roster()]
        sig = chain_sig(doc, roster_ids)
        ch = load_chain()
        if not (_chain_age_ok(cfg, sig) and not _chain_running()):
            if not _chain_running():
                _save_json(CHAIN_STATE_F, {"sig": sig, "running": True, "run_ts": time.time()})
                _fire_chain_worker(roster_ids)
            op = _load_json(pr.LATEST_JSON) or {}
            return {"one_pager": dict(op, pending=True), "llm_chain": ch}
        op = pr.maybe_run(doc)
        return {"one_pager": dict(op or {}), "llm_chain": ch}


