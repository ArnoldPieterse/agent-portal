# ---- parsing + validation ----------------------------------------------------------

def _parse_json(raw):
    pr = _pr()
    t = pr._strip_fences(raw or "")
    try:
        return json.loads(t)
    except Exception:
        try:
            return json.loads(pr._close_truncated(t))
        except Exception:
            return None


def _day_span(s, max_day):
    m = re.search(r"day\s*(\d+)(?:\s*-\s*(\d+))?", str(s or ""))
    if not m:
        return None
    a = int(m.group(1))
    b = int(m.group(2)) if m.group(2) else a
    if not (0 <= a <= b <= max_day):
        return None
    return a, b


def validate_30d(raw, refs, roster_ids):
    data = _parse_json(raw)
    outs = data.get("outcomes") if isinstance(data, dict) else data
    if not isinstance(outs, list) or not (3 <= len(outs) <= 12):
        return None, {"error": "bad-outcome-count"}
    pr = _pr()
    clean, grounded_n, missing = [], 0, []
    for o in outs:
        if not isinstance(o, dict):
            continue
        name = str(o.get("name") or "").strip()[:160]
        span = _day_span(o.get("window"), 60)
        if not name or not span or span[0] < 1:
            continue
        lane = str(o.get("lane") or "").strip().lower()
        if lane and lane not in roster_ids and lane != "fleet":
            lane = "fleet"
        gates = [str(g).strip()[:200] for g in (o.get("gates") or []) if str(g).strip()][:6]
        entry = {"name": name, "window": "day %d-%d" % span,
                 "status": str(o.get("status") or "planned").strip()[:120],
                 "lane": lane or "fleet", "gates": gates,
                 "note": str(o.get("note") or "").strip()[:240]}
        if o.get("cycle_closing"):
            entry["cycle_closing"] = True
        g = pr.is_grounded(name, refs) or any(pr.is_grounded(g_, refs) for g_ in gates)
        grounded_n += 1 if g else 0
        if not g:
            missing.append(name[:60])
        clean.append(entry)
    if len(clean) < 3:
        return None, {"error": "too-few-valid"}
    ratio = grounded_n / len(clean)
    stats = {"outcomes": len(clean), "grounded": grounded_n, "ratio": round(ratio, 2),
             "missing": missing[:6]}
    if ratio < _pr().GROUND_FLOOR:
        return None, dict(stats, error="low-grounding %.0f%%" % (100 * ratio))
    return clean, stats


def _validate_derived(raw, prev_entries, refs, max_day):
    """Shared validator for the 15d/7d rounds (entries with steps, parent-linked)."""
    data = _parse_json(raw)
    entries = data.get("entries") if isinstance(data, dict) else data
    if not isinstance(entries, list) or not (3 <= len(entries) <= 16):
        return None, {"error": "bad-entry-count"}
    pr = _pr()
    prev_names = [str(e.get("name") or "").lower() for e in prev_entries if e.get("name")]
    refs2 = list(refs)
    for e in prev_entries:
        refs2.append(str(e.get("name") or ""))
        for s in e.get("steps") or []:
            refs2.append(str(s.get("text") or ""))
    clean, grounded_n, missing = [], 0, []
    for e in entries:
        if not isinstance(e, dict):
            continue
        name = str(e.get("name") or "").strip()[:160]
        span = _day_span(e.get("window"), max_day)
        steps_in = e.get("steps") or []
        if not name or not span or not isinstance(steps_in, list):
            continue
        steps = []
        for s in steps_in[:8]:
            if not isinstance(s, dict):
                continue
            ss = _day_span(s.get("days"), max_day)
            txt = str(s.get("text") or "").strip()[:240]
            if ss and txt:
                steps.append({"days": "day %d-%d" % ss, "text": txt})
        if not steps:
            continue
        parent = str(e.get("parent") or "").strip()[:160] or None
        if parent and parent.lower() not in prev_names:
            parent = None
        entry = {"name": name, "parent": parent, "window": "day %d-%d" % span,
                 "status": str(e.get("status") or "").strip()[:160], "steps": steps}
        nm = name.lower()
        g = (nm in prev_names or any(nm.startswith(p) or p in nm for p in prev_names)) \
            or pr.is_grounded(name, refs2) \
            or any(pr.is_grounded(s["text"], refs2) for s in steps)
        grounded_n += 1 if g else 0
        if not g:
            missing.append(name[:60])
        clean.append(entry)
    if len(clean) < 3:
        return None, {"error": "too-few-valid"}
    ratio = grounded_n / len(clean)
    stats = {"entries": len(clean), "grounded": grounded_n, "ratio": round(ratio, 2),
             "missing": missing[:6]}
    if ratio < _pr().GROUND_FLOOR:
        return None, dict(stats, error="low-grounding %.0f%%" % (100 * ratio))
    return clean, stats


# ---- judging ---------------------------------------------------------------------------

JUDGE_CHAIN_SYSTEM = ("You are %s, the judge in a fleet planning round. Three planners each drafted the "
                      "%s plan independently from the same input. Compare them and pick the best.")

JUDGE_CHAIN_CONTRACT = ('Score each draft 0-5 on: grounding (traces to the live state / parent plan), '
                        'coverage (all outcomes that belong in this horizon), day-fit (windows/steps pinned '
                        'to real days and gate ETAs), actionability. Respond with ONLY a JSON object: '
                        '{"winner": "A"|"B"|"C", "scores": {"A": 0-5, "B": 0-5, "C": 0-5}, '
                        '"rationale": "<two sentences>"}')


def judge_chain(judge_agent, labelled, horizon, context):
    """labelled = [(label, parsed_list, stats)] -> verdict dict or None."""
    pr = _pr()
    body = []
    for label, parsed, stats in labelled:
        body.append("DRAFT %s (grounded %.0f%%):\n%s" % (
            label, 100 * stats.get("ratio", 0), json.dumps(parsed)[:4200]))
    user = "Round input (what the planners were given - judge grounding against this):\n%s\n\n%s\n\n%s" % (
        context[:4500], "\n\n".join(body), JUDGE_CHAIN_CONTRACT)
    try:
        raw = pr.llm_call(judge_agent, JUDGE_CHAIN_SYSTEM % (judge_agent["id"], horizon), user,
                          max_tokens=900, temperature=0.0, timeout=pr.JUDGE_TIMEOUT_S, model=judge_agent[1])
        v = json.loads(pr._strip_fences(raw))
    except Exception:
        return None
    if not isinstance(v, dict) or v.get("winner") not in [l for l, _p, _s in labelled]:
        return None
    return {"agent": judge_agent["id"], "winner": v["winner"],
            "scores": v.get("scores") or {}, "rationale": str(v.get("rationale") or "")[:400]}


def local_pick_chain(labelled, prev_names):
    """Deterministic tie-break when no live judge: grounding x4 + coverage x3 + day-fit bonus."""
    scored = {}
    for label, parsed, stats in labelled:
        names = {str(e.get("name") or "").lower() for e in parsed}
        cov = 0.0
        if prev_names:
            hit = sum(1 for pn in prev_names
                      if any(pn == n or pn in n or n.startswith(pn) for n in names))
            cov = hit / len(prev_names)
        s = stats.get("ratio", 0) * 4.0 + cov * 3.0
        if not stats.get("missing"):
            s += 0.5
        scored[label] = round(s, 2)
    best = max(scored, key=scored.get)
    return {"agent": "local-rubric", "winner": best, "scores": scored,
            "rationale": "judge seat unavailable - local rubric: grounding x4 + coverage x3 + day-fit bonus"}


# ---- one horizon round -------------------------------------------------------------------

def _round(horizon, system_tpl, user_prompt, validator, prev_names, crew):
    """3 parallel planner drafts -> judge (or local rubric) -> selected plan list."""
    pr = _pr()
    planners, judge = crew
    planners = planners[:3]

    def draft_one(i_am):
        agent, model = i_am
        try:
            raw = pr.llm_call(agent, system_tpl % agent["id"], user_prompt,
                              max_tokens=4000, temperature=0.2,
                              timeout=pr.DRAFT_TIMEOUT_S, model=model)
        except Exception as e:
            return {"error": str(e)[:120]}
        if not raw:
            return {"error": "no-response"}
        parsed, stats = validator(raw)
        if parsed is None:
            return stats
        return (parsed, stats)

    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as ex:
        futs = [ex.submit(draft_one, am) for am in planners]
        results = []
        for f in futs:
            try:
                results.append(f.result())
            except Exception as e:
                results.append({"error": str(e)[:120]})

    labelled, draft_stats = [], []
    for i, am in enumerate(planners):
        r = results[i]
        if isinstance(r, tuple):
            parsed, stats = r
            labelled.append((LABELS[i], parsed, stats))
            draft_stats.append({"label": LABELS[i], "agent": am[0]["id"], "model": am[1], "stats": stats})
        else:
            draft_stats.append({"label": LABELS[i], "agent": am[0]["id"], "model": am[1],
                                "stats": r or {"error": "unknown"}})

    if not labelled:
        return None, "deterministic-fallback", None, draft_stats
    if len(labelled) == 1:
        verdict = {"agent": "sole-draft", "winner": labelled[0][0], "scores": {},
                   "rationale": "only one valid draft"}
        source = "llm-single-draft"
    else:
        verdict = None
        if judge is not None:
            verdict = judge_chain(judge, labelled, horizon, user_prompt)
        if verdict is None:
            verdict = local_pick_chain(labelled, prev_names)
            source = "llm-judge-local"
        else:
            source = "llm-3+1"
    w = next((x for x in labelled if x[0] == verdict["winner"]), labelled[0])
    return w[1], source, verdict, draft_stats


